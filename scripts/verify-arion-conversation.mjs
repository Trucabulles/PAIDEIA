import assert from 'node:assert/strict';
import { createServer } from 'vite';
const vite = await createServer({configFile:false,server:{middlewareMode:true},appType:'custom',logLevel:'silent'});
try {
  const engine = await vite.ssrLoadModule('/src/features/designer-actions/designerActionEngine.ts');
  const {prepareDesignerFollowUp}=await vite.ssrLoadModule('/src/features/designer-actions/designerFollowUp.ts');
  const understanding = await vite.ssrLoadModule('/src/features/designer-actions/designerUnderstanding.ts');
  const {selectDesignerUndoTargets: selectUndo}=await vite.ssrLoadModule('/src/features/designer-actions/designerUndo.ts');
  const targets=['continueButtonLabel','continueButtonBackgroundColor','continueButtonTextColor'].map(property=>({property}));
  assert.equal(selectUndo('annule le changement de libellé',targets).targets.length,1);
  assert.equal(selectUndo('annule tout le lot',targets).targets.length,3);
  assert.ok(selectUndo('annule la couleur',targets).clarification);
  assert.ok(selectUndo('annule la modification étrange',targets).clarification);
  assert.ok(understanding.validateUnderstanding([null]).length);
  const rule={id:'test',capabilityId:'activity-spacing',phrases:['Aérer les activités'],patterns:[],positive:['AÉRER LES ACTIVITÉS !'],negative:['Aérer la pièce']};
  assert.deepEqual(understanding.validateUnderstanding([rule]),[]);
  assert.ok(understanding.validateUnderstanding([{...rule,negative:['aérer les activités']}]).length);
  assert.ok(understanding.validateUnderstanding([{...rule,patterns:['[']}]).length);
  assert.equal(engine.parseDesignerConversationTurn('les activités sont trop serrées').status,'incomplete');
  const typo=engine.parseDesignerConversationTurn('les activités sont trop serrés');
  assert.equal(typo.question,'understanding-choice');
  assert.equal(engine.parseDesignerConversationTurn('oui',typo.draft).status,'incomplete');
  assert.equal(engine.parseDesignerConversationTurn('aucune',typo.draft).status,'cancelled');
  const batch=engine.parseDesignerConversationTurn('Mets les boutons Continuer en bleu puis change leur libellé en "Suivant"');
  assert.equal(batch.status,'ready',JSON.stringify(batch));
  assert.equal(prepareDesignerFollowUp('finalement seulement ce chapitre',batch.intent).intent.scope,'chapter');
  assert.equal(engine.parseDesignerConversationTurn(prepareDesignerFollowUp('et mets leur texte en blanc',batch.intent).command).status,'ready');
  assert.deepEqual(batch.intent.operations.map(item=>item.kind),['set-continue-button-background','set-continue-button-label']);
  const pending=engine.parseDesignerConversationTurn('Change la couleur des boutons Continuer puis change leur libellé en "Suivant"');
  assert.equal(pending.status,'incomplete');
  const completed=engine.parseDesignerConversationTurn('bleu',pending.draft);
  assert.equal(completed.status,'ready',JSON.stringify(completed));
  assert.equal(completed.intent.operations.length,2);
  const unknown=engine.parseDesignerConversationTurn('Mets les boutons Continuer en bleu puis abracadabra');
  assert.equal(unknown.question,'unresolved-action');
  assert.equal(unknown.draft.operations.length,1);
  const repaired=engine.parseDesignerConversationTurn('Change le libellé des boutons Continuer en "Après"',unknown.draft);
  assert.equal(repaired.status,'ready');
  assert.equal(repaired.intent.operations.length,2);
  const quoted=engine.parseDesignerConversationTurn('Change le libellé des boutons Continuer en "Lire puis continuer"');
  assert.equal(quoted.status,'ready');
  assert.equal(quoted.intent.operations[0].label,'Lire puis continuer');
  console.log('Arion : règles déclaratives, lots, précision et libellés préservés.');
} finally {await vite.close();}
