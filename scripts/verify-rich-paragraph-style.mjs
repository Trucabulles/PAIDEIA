import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { Window } from 'happy-dom';
const window = new Window();
globalThis.document = window.document;
globalThis.Node = window.Node;
globalThis.Text = window.Text;
globalThis.Element = window.Element;
globalThis.HTMLElement = window.HTMLElement;
globalThis.HTMLParagraphElement = window.HTMLParagraphElement;
globalThis.HTMLSpanElement = window.HTMLSpanElement;
globalThis.Range = window.Range;
const output = await build({ entryPoints:['src/app/richTextParagraphStyle.ts'], bundle:true, platform:'node', format:'esm', write:false });
const module = await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].text).toString('base64')}`);
const apply = module.applyRichParagraphStyle;
const editor = document.createElement('div');
document.body.append(editor);
editor.innerHTML = '<ul><li><h1><span style="font-size:71px">one</span></h1></li><li><p>two</p></li></ul>';
let range = document.createRange();
range.selectNodeContents(editor.querySelector('span'));
assert.equal(apply(editor, range, 'h2'), true);
assert.equal(editor.querySelectorAll('li').length, 2);
assert.equal(editor.querySelector('h2').textContent, 'one');
assert.equal(editor.querySelector('span').style.fontSize, '');
range.selectNodeContents(editor.querySelector('h2'));
apply(editor, range, 'p');
assert.equal(editor.querySelector('h2'), null);
editor.innerHTML = '<table><tbody><tr><td><p>one</p></td><td><p>two</p></td></tr><tr><td><p>three</p></td><td><p>four</p></td></tr></tbody></table>';
range.selectNodeContents(editor.querySelectorAll('p')[2]);
apply(editor, range, 'h3');
assert.equal(editor.querySelectorAll('h3').length, 1);
assert.equal(editor.querySelector('h3').textContent, 'three');
assert.equal(editor.querySelectorAll('td').length, 4);
editor.querySelector('h3').innerHTML='<span style="font-size:90px">three</span>';
range.selectNodeContents(editor.querySelector('h3'));
apply(editor, range, 'h3');
assert.equal(editor.querySelector('span').style.fontSize, '');
console.log('Paragraph/list/table semantic formatting: passed');
